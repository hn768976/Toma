export type Sheet = {
  id: string;
  title: string;
  ink: string;
  /** Seed key: sheets that share it draw identical elements (C1/C2). */
  seedKey: string;
  cols: number;
  rows: number;
  /** Element half-size in px at 4K. */
  S: number;
  gens: G.Gen[];
};

const highlightBox: G.Gen = (rng, S) =>
  roughStrokes({ kind: "rectangle", x: -0.9 * S, y: -0.55 * S, w: 1.8 * S, h: 1.1 * S }, hash("hl", rng()), {
    roughness: 1,
    fill: "x",
    fillStyle: "hachure",
    hachureGap: S * 0.12,
    hachureAngle: -35,
    disableMultiStroke: true,
    disableMultiStrokeFill: true,
    join: S * 0.05,
  }).map((pts, i) => ({ pts, weight: i === 0 ? 1 : 0.6 }));

const wideBorder: G.Gen = (rng, S) => {
  const box = (k: number) => G.outline(rng, [[-S * k, -S * 0.12 * k], [S * k, -S * 0.12 * k], [S * k, S * 0.12 * k], [-S * k, S * 0.12 * k]], true, 0.01);
  return [{ pts: box(1) }, { pts: box(0.96) }];
};

const roughBorder: G.Gen = (rng, S) =>
  roughStrokes({ kind: "rectangle", x: -S, y: -0.13 * S, w: 2 * S, h: 0.26 * S }, hash("rb", rng()), { roughness: 1.2, bowing: 2 }).map((pts) => ({ pts }));

