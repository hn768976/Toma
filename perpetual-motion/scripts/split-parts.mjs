// Anatomy writes a figure as one flat run of anonymous <g class="iso-solid">
// groups with paths already projected to the screen, and no pivots. To animate
// it we need each moving part on its own, with the plane it turns in. This
// script reads art/raw/<id>.svg (parts marked data-part by build-art.mjs) and:
//
//   1. splits it into one named group per part: id="<machine>-<part>";
//   2. records each turning part's pivot and plane (data-face, data-along);
//   3. fixes two kit quirks: fills and tops with an inner hole (ringBand,
//      lathe with `hole`) get fill-rule="evenodd", since the kit winds the
//      hole the same way as the hull; and anatomy's blurred `iso-halo` paths are dropped
//      (the video draws its soft floor shadows itself, dithered);
//   4. strips attributes only the anatomy line checker reads (data-free);
//   5. writes art/svg/<id>.svg (named groups, rest pose, styled) and
//      src/generated/<id>.ts (the part strings and the camera for React).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { LOOKS, lookCss } from "../src/lib/look.ts";
import { faceOf, faceAffine, matrixText } from "../src/lib/iso.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const only = process.argv.slice(2);
const machines = ["overbalanced", "watermill", "flask", "magnet", "rollingball"].filter((id) => !only.length || only.includes(id));

const unesc = (s) => s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");

/** Top-level <g data-part> groups, found by counting <g> depth. */
function topGroups(svg) {
  const out = [];
  const re = /<g\b[^>]*>|<\/g>/g;
  let depth = 0;
  let start = -1;
  let open = "";
  let m;
  while ((m = re.exec(svg))) {
    if (m[0] === "</g>") {
      depth--;
      if (depth === 0) out.push({ open, inner: svg.slice(start, m.index) });
    } else {
      if (depth === 0) {
        open = m[0];
        start = m.index + m[0].length;
      }
      if (!m[0].endsWith("/>")) depth++;
    }
  }
  return out;
}

function clean(inner) {
  let fixedHoles = 0;
  let halos = 0;
  let s = inner.replace(/<path class="iso-halo"[^>]*\/>/g, () => {
    halos++;
    return "";
  });
  s = s.replace(/<path class="(iso-fill|iso-top)" d="([^"]*)"\/>/g, (all, cls, d) => {
    if ((d.match(/M/g) || []).length < 2) return all;
    fixedHoles++;
    return `<path class="${cls}" fill-rule="evenodd" d="${d}"/>`;
  });
  s = s.replace(/ data-free="[^"]*"/g, "").replace(/ data-free(?=[ >\/])/g, "");
  return { s, fixedHoles, halos };
}

const faceFor = (spec, origin) => {
  if (spec === "x") return faceOf(origin, [0, -1, 0], [0, 0, -1]);
  if (spec === "y") return faceOf(origin, [1, 0, 0], [0, 0, -1]);
  return faceOf(spec.origin, spec.u, spec.v);
};

for (const id of machines) {
  const raw = readFileSync(join(root, "art", "raw", `${id}.svg`), "utf8");
  const meta = JSON.parse(unesc(raw.match(/<metadata id="pm-meta">([\s\S]*?)<\/metadata>/)[1]));
  const groups = topGroups(raw.replace(/<metadata[\s\S]*?<\/metadata>/, ""));
  const parts = {};
  const report = [];
  let named = "";
  for (const g of groups) {
    const name = g.open.match(/data-part="([^"]+)"/)[1];
    const info = meta.parts.find((p) => p.name === name);
    const { s, fixedHoles, halos } = clean(g.inner);
    parts[name] = s;
    report.push(`${name}${info.kind === "flat" ? "*" : ""}${fixedHoles ? ` (+${fixedHoles} evenodd)` : ""}${halos ? ` (-${halos} halo)` : ""}`);
    const gid = `${id}-${name}`;
    if (info.kind === "flat") {
      const origin = info.origin ?? meta.extra.origin;
      const face = faceFor(info.face, origin);
      const along = info.along ? (info.along[0] + info.along[1]) / 2 : 0;
      const rest = info.restTransform ?? "";
      named += `<g id="${gid}" data-kind="flat" data-face='${JSON.stringify({ origin: face.origin, u: face.u, v: face.v })}' data-along="${(info.along ?? [0, 0]).join(",")}" transform="${matrixText(faceAffine(meta.P, face, along))}${rest ? " " + rest : ""}">${s}</g>\n`;
    } else {
      named += `<g id="${gid}" data-kind="static">${s}</g>\n`;
    }
  }
  const css = lookCss(LOOKS.workshop);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" class="pm" viewBox="0 0 3840 2160" width="3840" height="2160"><style>${css}</style><rect width="3840" height="2160" fill="${LOOKS.workshop.background}"/>\n${named}</svg>\n`;
  mkdirSync(join(root, "art", "svg"), { recursive: true });
  writeFileSync(join(root, "art", "svg", `${id}.svg`), svg);
  const ts =
    `// Generated by scripts/split-parts.mjs from art/raw/${id}.svg. Do not edit.\n` +
    `import type { Projection } from "../kit/iso-kit.ts";\n` +
    `import type { FloorShadow } from "../lib/Backdrop.tsx";\n` +
    `export const P: Projection = ${JSON.stringify(meta.P)};\n` +
    `export const shadows: FloorShadow[] = ${JSON.stringify(meta.shadows)};\n` +
    `export const grid = ${JSON.stringify(meta.grid)};\n` +
    `export const extra = ${JSON.stringify(meta.extra)} as const;\n` +
    `export const parts = ${JSON.stringify(parts, null, 0)} as const;\n`;
  mkdirSync(join(root, "src", "generated"), { recursive: true });
  writeFileSync(join(root, "src", "generated", `${id}.ts`), ts);
  console.log(`${id}: ${report.join(", ")}  (* = flat, turns in its plane)`);
}
