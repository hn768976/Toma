/** Shared GLSL snippets (WebGL2 / GLSL ES 3.0 compatible, also valid in three's GLSL1 mode). */

/** 3D simplex noise (Ashima Arts / Stefan Gustavson, MIT). Returns about -1..1. */
export const SIMPLEX3 = /* glsl */ `
vec3 mod289(vec3 x) { return x - floor(x * (1.0 / 289.0)) * 289.0; }
vec4 mod289(vec4 x) { return x - floor(x * (1.0 / 289.0)) * 289.0; }
vec4 permute(vec4 x) { return mod289(((x * 34.0) + 10.0) * x); }
vec4 taylorInvSqrt(vec4 r) { return 1.79284291400159 - 0.85373472095314 * r; }
float snoise(vec3 v) {
  const vec2 C = vec2(1.0 / 6.0, 1.0 / 3.0);
  const vec4 D = vec4(0.0, 0.5, 1.0, 2.0);
  vec3 i = floor(v + dot(v, C.yyy));
  vec3 x0 = v - i + dot(i, C.xxx);
  vec3 g = step(x0.yzx, x0.xyz);
  vec3 l = 1.0 - g;
  vec3 i1 = min(g.xyz, l.zxy);
  vec3 i2 = max(g.xyz, l.zxy);
  vec3 x1 = x0 - i1 + C.xxx;
  vec3 x2 = x0 - i2 + C.yyy;
  vec3 x3 = x0 - D.yyy;
  i = mod289(i);
  vec4 p = permute(permute(permute(i.z + vec4(0.0, i1.z, i2.z, 1.0)) + i.y + vec4(0.0, i1.y, i2.y, 1.0)) + i.x + vec4(0.0, i1.x, i2.x, 1.0));
  float n_ = 0.142857142857;
  vec3 ns = n_ * D.wyz - D.xzx;
  vec4 j = p - 49.0 * floor(p * ns.z * ns.z);
  vec4 x_ = floor(j * ns.z);
  vec4 y_ = floor(j - 7.0 * x_);
  vec4 x = x_ * ns.x + ns.yyyy;
  vec4 y = y_ * ns.x + ns.yyyy;
  vec4 h = 1.0 - abs(x) - abs(y);
  vec4 b0 = vec4(x.xy, y.xy);
  vec4 b1 = vec4(x.zw, y.zw);
  vec4 s0 = floor(b0) * 2.0 + 1.0;
  vec4 s1 = floor(b1) * 2.0 + 1.0;
  vec4 sh = -step(h, vec4(0.0));
  vec4 a0 = b0.xzyw + s0.xzyw * sh.xxyy;
  vec4 a1 = b1.xzyw + s1.xzyw * sh.zzww;
  vec3 p0 = vec3(a0.xy, h.x);
  vec3 p1 = vec3(a0.zw, h.y);
  vec3 p2 = vec3(a1.xy, h.z);
  vec3 p3 = vec3(a1.zw, h.w);
  vec4 norm = taylorInvSqrt(vec4(dot(p0, p0), dot(p1, p1), dot(p2, p2), dot(p3, p3)));
  p0 *= norm.x; p1 *= norm.y; p2 *= norm.z; p3 *= norm.w;
  vec4 m = max(0.5 - vec4(dot(x0, x0), dot(x1, x1), dot(x2, x2), dot(x3, x3)), 0.0);
  m = m * m;
  return 105.0 * dot(m * m, vec4(dot(p0, x0), dot(p1, x1), dot(p2, x2), dot(p3, x3)));
}
`;

/** Integer-free hashes (Dave Hoskins, MIT). Deterministic functions of their inputs. */
export const HASH = /* glsl */ `
float hash12(vec2 p) {
  vec3 p3 = fract(vec3(p.xyx) * 0.1031);
  p3 += dot(p3, p3.yzx + 33.33);
  return fract((p3.x + p3.y) * p3.z);
}
vec2 hash22(vec2 p) {
  vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973));
  p3 += dot(p3, p3.yzx + 33.33);
  return fract((p3.xx + p3.yz) * p3.zy);
}
vec3 hash32(vec2 p) {
  vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973));
  p3 += dot(p3, p3.yxz + 33.33);
  return fract((p3.xxy + p3.yzz) * p3.zyx);
}
`;

/**
 * Final-pass finishing: linear -> sRGB, film grain (~1.5 %) and +/-1/255 triangular dither.
 * Grain is a fixed hash of (pixel, frame % 600); never Math.random().
 * darkFade > 0 fades grain to zero below that sRGB luminance (Smoke Orb: 0.03),
 * and fades dither out only at true black so the background stays exactly 0.
 */
export const FINISH = /* glsl */ `
vec3 linearToSrgb(vec3 c) {
  c = max(c, vec3(0.0));
  return mix(c * 12.92, 1.055 * pow(c, vec3(1.0 / 2.4)) - 0.055, step(vec3(0.0031308), c));
}
float finishHash(vec2 p) {
  vec3 p3 = fract(vec3(p.xyx) * 0.1031);
  p3 += dot(p3, p3.yzx + 33.33);
  return fract((p3.x + p3.y) * p3.z);
}
vec3 finish(vec3 srgb, vec2 fragCoord, float frame, float grainAmt, float darkFade) {
  vec2 fo = vec2(mod(frame * 7.0, 61.0) * 13.37, mod(frame * 11.0, 53.0) * 7.31);
  float g1 = finishHash(fragCoord + fo);
  float g2 = finishHash(fragCoord * 1.31 + fo.yx + 17.0);
  float grain = (g1 + g2 - 1.0);               // triangular, -1..1
  float lum = dot(srgb, vec3(0.2126, 0.7152, 0.0722));
  float gk = grainAmt;
  float dk = 1.0;
  if (darkFade > 0.0) {
    gk *= smoothstep(0.0, darkFade, lum);
    dk = smoothstep(0.0, 1.5 / 255.0, lum);
  }
  srgb += grain * gk;
  float d1 = finishHash(fragCoord + fo * 1.7 + 101.0);
  float d2 = finishHash(fragCoord * 0.93 + fo.yx * 2.3 + 59.0);
  srgb += (d1 + d2 - 1.0) * (1.0 / 255.0) * dk;  // +/-1/255
  return clamp(srgb, 0.0, 1.0);
}
`;

/** Soft highlight shoulder: identity below 0.75, rolls off smoothly towards 1. */
export const SHOULDER = /* glsl */ `
vec3 shoulder(vec3 c) {
  vec3 k = vec3(0.75);
  vec3 over = max(c - k, 0.0);
  return min(c, k) + (1.0 - k) * (1.0 - exp(-over / (1.0 - k)));
}
`;
