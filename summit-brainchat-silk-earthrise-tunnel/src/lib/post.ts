// Deterministic post pipeline, all in half-float:
//   scene (MSAA x4, HalfFloat, depth texture)
//   -> [SSAO, fixed 4x4 kernel rotation, box-resolved]   (optional)
//   -> prep (colour * AO, signed circle of confusion in alpha)
//   -> [DoF gather at half res, golden-angle disc, then CoC blend]  (optional)
//   -> bloom (soft-knee prefilter, 6-level down/up chain)
//   -> composite: exposure, vignette, ACES, sRGB, grain + ±1/255 dither.
// No temporal accumulation of any kind: each frame depends only on the
// scene state that the caller derived from the frame number.
import * as THREE from "three";
import { HASH } from "./glsl";

export type DofParams = {
  /** Focus distance in world units (camera space). */
  focus: number;
  /** CoC (fraction of frame height) at infinity, signed formula aperture*(1-focus/z). */
  aperture: number;
  /** CoC clamp as a fraction of frame height. */
  maxCoc: number;
  /** Extra multiplier on near-field (in front of focus) blur. */
  nearScale?: number;
};

export type PostParams = {
  exposure: number;
  bloomStrength: number;
  bloomThreshold: number;
  bloomKnee: number;
  /** 0..1, how much of each coarser bloom level is blended into the finer one. */
  bloomRadius: number;
  dof?: DofParams;
  ao?: { radius: number; strength: number; bias: number };
  vignette: number;
  /** Grain amplitude in display space (0.015 = 1.5 %). */
  grain: number;
  /** If > 0, grain fades to zero below this display luminance. */
  grainFadeLum: number;
  saturation?: number;
  /** Lift / gain in display space after tonemapping. */
  lift?: number;
  /** Optional colour multiply in linear space before tonemap. */
  tint?: THREE.Color;
};

const FS_VERT = /* glsl */ `
out vec2 vUv;
void main(){ vUv = uv; gl_Position = vec4(position.xy, 0.0, 1.0); }
`;

function fsTriangle() {
  const g = new THREE.BufferGeometry();
  g.setAttribute("position", new THREE.Float32BufferAttribute([-1, -1, 0, 3, -1, 0, -1, 3, 0], 3));
  g.setAttribute("uv", new THREE.Float32BufferAttribute([0, 0, 2, 0, 0, 2], 2));
  return g;
}

function mat(frag: string, uniforms: Record<string, THREE.IUniform>) {
  return new THREE.ShaderMaterial({
    vertexShader: FS_VERT,
    fragmentShader: frag,
    uniforms,
    depthTest: false,
    depthWrite: false,
  });
}

function rt(w: number, h: number, opts: Partial<THREE.RenderTargetOptions> = {}) {
  return new THREE.WebGLRenderTarget(Math.max(1, w), Math.max(1, h), {
    type: THREE.HalfFloatType,
    format: THREE.RGBAFormat,
    minFilter: THREE.LinearFilter,
    magFilter: THREE.LinearFilter,
    depthBuffer: false,
    generateMipmaps: false,
    ...opts,
  });
}

// 16 hemisphere kernel samples, fixed (generated by a closed formula).
function aoKernel() {
  const out: THREE.Vector3[] = [];
  const n = 16;
  for (let i = 0; i < n; i++) {
    const u = (i + 0.5) / n;
    const phi = i * 2.399963229728653;
    const cosT = Math.sqrt(1 - u * 0.95);
    const sinT = Math.sqrt(1 - cosT * cosT);
    let scale = (i + 1) / n;
    scale = 0.15 + 0.85 * scale * scale;
    out.push(new THREE.Vector3(Math.cos(phi) * sinT, Math.sin(phi) * sinT, cosT).multiplyScalar(scale));
  }
  return out;
}

export class PostPipeline {
  readonly width: number;
  readonly height: number;
  private renderer: THREE.WebGLRenderer;
  private sceneRT: THREE.WebGLRenderTarget;
  private aoRT: THREE.WebGLRenderTarget;
  private prepRT: THREE.WebGLRenderTarget;
  private dofHalfRT: THREE.WebGLRenderTarget;
  private dofRT: THREE.WebGLRenderTarget;
  private down: THREE.WebGLRenderTarget[] = [];
  private up: THREE.WebGLRenderTarget[] = [];
  private quadScene = new THREE.Scene();
  private quadCam = new THREE.OrthographicCamera(-1, 1, 1, -1, 0, 1);
  private quad: THREE.Mesh;
  private mAO: THREE.ShaderMaterial;
  private mPrep: THREE.ShaderMaterial;
  private mDof: THREE.ShaderMaterial;
  private mDofCombine: THREE.ShaderMaterial;
  private mDown: THREE.ShaderMaterial;
  private mUp: THREE.ShaderMaterial;
  private mComposite: THREE.ShaderMaterial;

  constructor(renderer: THREE.WebGLRenderer, width: number, height: number) {
    this.renderer = renderer;
    this.width = width;
    this.height = height;
    const depthTexture = new THREE.DepthTexture(width, height, THREE.FloatType);
    depthTexture.format = THREE.DepthFormat;
    this.sceneRT = new THREE.WebGLRenderTarget(width, height, {
      type: THREE.HalfFloatType,
      format: THREE.RGBAFormat,
      samples: 4,
      depthBuffer: true,
      depthTexture,
      minFilter: THREE.LinearFilter,
      magFilter: THREE.LinearFilter,
    });
    this.aoRT = rt(width, height);
    this.prepRT = rt(width, height);
    const hw = Math.ceil(width / 2), hh = Math.ceil(height / 2);
    this.dofHalfRT = rt(hw, hh);
    this.dofRT = rt(width, height);
    let w = width, h = height;
    for (let i = 0; i < 7; i++) {
      w = Math.max(1, Math.ceil(w / 2));
      h = Math.max(1, Math.ceil(h / 2));
      this.down.push(rt(w, h));
      this.up.push(rt(w, h));
    }

    this.quad = new THREE.Mesh(fsTriangle());
    this.quad.frustumCulled = false;
    this.quadScene.add(this.quad);

    this.mAO = mat(
      /* glsl */ `
      precision highp float;
      in vec2 vUv;
      uniform sampler2D tDepth;
      uniform mat4 uProj, uInvProj;
      uniform vec2 uRes;
      uniform float uRadius, uBias;
      uniform vec3 uKernel[16];
      vec3 viewPos(vec2 uv){
        float d = texture(tDepth, uv).x;
        vec4 v = uInvProj * vec4(uv*2.0-1.0, d*2.0-1.0, 1.0);
        return v.xyz / v.w;
      }
      void main(){
        float d = texture(tDepth, vUv).x;
        if (d >= 0.99999) { gl_FragColor = vec4(1.0); return; }
        vec3 P = viewPos(vUv);
        vec2 px = 1.0 / uRes;
        vec3 Px = viewPos(vUv + vec2(px.x,0.0)) - P, Px2 = P - viewPos(vUv - vec2(px.x,0.0));
        vec3 Py = viewPos(vUv + vec2(0.0,px.y)) - P, Py2 = P - viewPos(vUv - vec2(0.0,px.y));
        vec3 dx = abs(Px.z) < abs(Px2.z) ? Px : Px2;
        vec3 dy = abs(Py.z) < abs(Py2.z) ? Py : Py2;
        vec3 N = normalize(cross(dx, dy));
        if (dot(N, -P) < 0.0) N = -N;
        // fixed 4x4 interleaved rotation pattern (resolved by a 4x4 box later)
        ivec2 ip = ivec2(gl_FragCoord.xy) & 3;
        float bayer[16] = float[16](0.,8.,2.,10.,12.,4.,14.,6.,3.,11.,1.,9.,15.,7.,13.,5.);
        float a = (bayer[ip.y*4+ip.x] + 0.5) / 16.0 * 6.2831853;
        vec3 rv = vec3(cos(a), sin(a), 0.0);
        vec3 T = normalize(rv - N * dot(rv, N));
        vec3 B = cross(N, T);
        mat3 tbn = mat3(T, B, N);
        float occ = 0.0;
        for (int i = 0; i < 16; i++){
          vec3 s = P + tbn * uKernel[i] * uRadius;
          vec4 c = uProj * vec4(s, 1.0);
          vec2 suv = c.xy / c.w * 0.5 + 0.5;
          float sz = viewPos(suv).z;
          float range = smoothstep(0.0, 1.0, uRadius / max(abs(P.z - sz), 1e-4));
          occ += (sz >= s.z + uBias ? 1.0 : 0.0) * range;
        }
        gl_FragColor = vec4(vec3(1.0 - occ / 16.0), 1.0);
      }`,
      {
        tDepth: { value: null },
        uProj: { value: new THREE.Matrix4() },
        uInvProj: { value: new THREE.Matrix4() },
        uRes: { value: new THREE.Vector2(width, height) },
        uRadius: { value: 0.3 },
        uBias: { value: 0.02 },
        uKernel: { value: aoKernel() },
      },
    );

    this.mPrep = mat(
      /* glsl */ `
      precision highp float;
      in vec2 vUv;
      uniform sampler2D tColor, tDepth, tAO;
      uniform vec2 uRes;
      uniform float uNear, uFar, uFocus, uAperture, uMaxCoc, uNearScale, uUseAO, uAOStrength, uUseDof;
      float viewZ(float d){
        // perspective depth -> positive view distance
        float ndc = d * 2.0 - 1.0;
        return (2.0 * uNear * uFar) / (uFar + uNear - ndc * (uFar - uNear));
      }
      void main(){
        vec3 c = texture(tColor, vUv).rgb;
        if (uUseAO > 0.5) {
          float ao = 0.0;
          for (int y = 0; y < 4; y++) for (int x = 0; x < 4; x++)
            ao += texture(tAO, vUv + (vec2(x, y) - 1.5) / uRes).r;
          ao /= 16.0;
          c *= mix(1.0, ao, uAOStrength);
        }
        float coc = 0.0;
        if (uUseDof > 0.5) {
          float z = viewZ(texture(tDepth, vUv).x);
          coc = uAperture * (1.0 - uFocus / z);
          if (coc < 0.0) coc *= uNearScale;
          coc = clamp(coc, -uMaxCoc, uMaxCoc) * uRes.y; // signed, in full-res pixels
        }
        gl_FragColor = vec4(c, coc);
      }`,
      {
        tColor: { value: null },
        tDepth: { value: null },
        tAO: { value: null },
        uRes: { value: new THREE.Vector2(width, height) },
        uNear: { value: 0.1 },
        uFar: { value: 100 },
        uFocus: { value: 10 },
        uAperture: { value: 0 },
        uMaxCoc: { value: 0.02 },
        uNearScale: { value: 1 },
        uUseAO: { value: 0 },
        uAOStrength: { value: 1 },
        uUseDof: { value: 0 },
      },
    );

    this.mDof = mat(
      /* glsl */ `
      precision highp float;
      in vec2 vUv;
      uniform sampler2D tPrep;
      uniform vec2 uTexel;      // full-res texel
      uniform float uMaxR;      // full-res px
      uniform int uN;
      void main(){
        vec4 C = texture(tPrep, vUv);
        float cc = abs(C.a);
        float wC = 1.0 / max(cc * cc, 1.0);
        vec3 sum = C.rgb * wC;
        float wsum = wC;
        float nearCov = 0.0;
        for (int i = 0; i < 200; i++){
          if (i >= uN) break;
          float fi = float(i) + 0.5;
          float r = sqrt(fi / float(uN)) * uMaxR;
          float ang = fi * 2.399963229728653;
          vec2 off = vec2(cos(ang), sin(ang)) * r;
          vec4 S = texture(tPrep, vUv + off * uTexel);
          float sc = abs(S.a);
          // a farther sample cannot blur over a nearer centre more than the centre's own CoC
          float cov = S.a > C.a ? min(sc, cc) : sc;
          float w = clamp(cov - r + 1.0, 0.0, 1.0) / max(cov * cov, 1.0);
          sum += S.rgb * w;
          wsum += w;
          if (S.a < 0.0 && S.a < C.a) nearCov = max(nearCov, clamp(sc - r + 1.0, 0.0, 1.0) * sc);
        }
        gl_FragColor = vec4(sum / wsum, nearCov);
      }`,
      {
        tPrep: { value: null },
        uTexel: { value: new THREE.Vector2(1 / width, 1 / height) },
        uMaxR: { value: 10 },
        uN: { value: 48 },
      },
    );

    this.mDofCombine = mat(
      /* glsl */ `
      precision highp float;
      in vec2 vUv;
      uniform sampler2D tPrep, tHalf;
      void main(){
        vec4 P = texture(tPrep, vUv);
        vec4 B = texture(tHalf, vUv);
        float k = smoothstep(0.6, 2.2, max(abs(P.a), B.a));
        gl_FragColor = vec4(mix(P.rgb, B.rgb, k), 1.0);
      }`,
      { tPrep: { value: null }, tHalf: { value: null } },
    );

    this.mDown = mat(
      /* glsl */ `
      precision highp float;
      in vec2 vUv;
      uniform sampler2D tSrc;
      uniform vec2 uTexel;  // source texel
      uniform float uPrefilter, uThreshold, uKnee;
      vec3 S(vec2 o){ return texture(tSrc, vUv + o * uTexel).rgb; }
      vec3 pre(vec3 c){
        float br = max(c.r, max(c.g, c.b));
        float soft = br - uThreshold + uKnee;
        soft = clamp(soft, 0.0, 2.0 * uKnee);
        soft = soft * soft / (4.0 * uKnee + 1e-5);
        float contrib = max(soft, br - uThreshold) / max(br, 1e-5);
        return c * contrib;
      }
      void main(){
        // 13-tap downsample (Jimenez 2014)
        vec3 a = S(vec2(-2,-2)), b = S(vec2(0,-2)), c = S(vec2(2,-2));
        vec3 d = S(vec2(-1,-1)), e = S(vec2(1,-1));
        vec3 f = S(vec2(-2,0)), g = S(vec2(0,0)), h = S(vec2(2,0));
        vec3 i = S(vec2(-1,1)), j = S(vec2(1,1));
        vec3 k = S(vec2(-2,2)), l = S(vec2(0,2)), m = S(vec2(2,2));
        vec3 o = (d+e+i+j)*0.125 + (a+b+f+g)*0.03125 + (b+c+g+h)*0.03125 + (f+g+k+l)*0.03125 + (g+h+l+m)*0.03125;
        if (uPrefilter > 0.5) o = pre(o);
        gl_FragColor = vec4(min(o, vec3(6e4)), 1.0);
      }`,
      {
        tSrc: { value: null },
        uTexel: { value: new THREE.Vector2() },
        uPrefilter: { value: 0 },
        uThreshold: { value: 1 },
        uKnee: { value: 0.5 },
      },
    );

    this.mUp = mat(
      /* glsl */ `
      precision highp float;
      in vec2 vUv;
      uniform sampler2D tCoarse, tFine;
      uniform vec2 uTexel; // coarse texel
      uniform float uRadius;
      vec3 S(vec2 o){ return texture(tCoarse, vUv + o * uTexel).rgb; }
      void main(){
        vec3 t = S(vec2(-1,-1)) + 2.0*S(vec2(0,-1)) + S(vec2(1,-1))
               + 2.0*S(vec2(-1,0)) + 4.0*S(vec2(0,0)) + 2.0*S(vec2(1,0))
               + S(vec2(-1,1)) + 2.0*S(vec2(0,1)) + S(vec2(1,1));
        t /= 16.0;
        gl_FragColor = vec4(texture(tFine, vUv).rgb + t * uRadius, 1.0);
      }`,
      { tCoarse: { value: null }, tFine: { value: null }, uTexel: { value: new THREE.Vector2() }, uRadius: { value: 0.8 } },
    );

    this.mComposite = mat(
      /* glsl */ `
      precision highp float;
      in vec2 vUv;
      uniform sampler2D tColor, tBloom;
      uniform float uBloom, uExposure, uVignette, uGrain, uGrainFade, uSat, uLift;
      uniform vec3 uTint;
      uniform vec2 uRes;
      uniform uint uFrame;
      ${HASH}
      vec3 aces(vec3 x){
        const float a=2.51, b=0.03, c=2.43, d=0.59, e=0.14;
        return clamp((x*(a*x+b))/(x*(c*x+d)+e), 0.0, 1.0);
      }
      vec3 toSRGB(vec3 c){
        return mix(c*12.92, 1.055*pow(c, vec3(1.0/2.4)) - 0.055, step(0.0031308, c));
      }
      void main(){
        vec3 c = texture(tColor, vUv).rgb + uBloom * texture(tBloom, vUv).rgb;
        c *= uExposure * uTint;
        vec2 q = vUv - 0.5;
        q.x *= uRes.x / uRes.y;
        float v = 1.0 - uVignette * smoothstep(0.35, 1.05, length(q));
        c *= v;
        float L = dot(c, vec3(0.2126, 0.7152, 0.0722));
        c = max(mix(vec3(L), c, uSat), 0.0);
        c = toSRGB(aces(c));
        c = uLift + (1.0 - uLift) * c;
        uvec3 key = uvec3(uvec2(gl_FragCoord.xy), uFrame);
        vec3 h1 = hash3(key);
        vec3 h2 = hash3(key + uvec3(7919u, 104729u, 1299709u));
        // monochrome film grain, triangular PDF, amplitude uGrain
        float g = (h1.x + h1.y - 1.0) * uGrain;
        float lum = dot(c, vec3(0.2126, 0.7152, 0.0722));
        if (uGrainFade > 0.0) g *= smoothstep(uGrainFade, 2.0 * uGrainFade, lum);
        c += g;
        // ±1/255 triangular dither for the 8-bit output
        c += (h2 - hash3(key + uvec3(31337u, 271828u, 3141592u))) / 255.0;
        gl_FragColor = vec4(clamp(c, 0.0, 1.0), 1.0);
      }`,
      {
        tColor: { value: null },
        tBloom: { value: null },
        uBloom: { value: 0.5 },
        uExposure: { value: 1 },
        uVignette: { value: 0.2 },
        uGrain: { value: 0.015 },
        uGrainFade: { value: 0 },
        uSat: { value: 1 },
        uLift: { value: 0 },
        uTint: { value: new THREE.Color(1, 1, 1) },
        uRes: { value: new THREE.Vector2(width, height) },
        uFrame: { value: 0 },
      },
    );
  }

  private pass(m: THREE.ShaderMaterial, target: THREE.WebGLRenderTarget | null) {
    this.quad.material = m;
    this.renderer.setRenderTarget(target);
    this.renderer.render(this.quadScene, this.quadCam);
  }

  render(scene: THREE.Scene, camera: THREE.PerspectiveCamera, p: PostParams, frame: number) {
    const r = this.renderer;
    r.setRenderTarget(this.sceneRT);
    r.setClearColor(0x000000, 1);
    r.clear(true, true, true);
    r.render(scene, camera);

    const useAO = !!p.ao;
    if (p.ao) {
      const u = this.mAO.uniforms;
      u.tDepth.value = this.sceneRT.depthTexture;
      u.uProj.value.copy(camera.projectionMatrix);
      u.uInvProj.value.copy(camera.projectionMatrixInverse);
      u.uRadius.value = p.ao.radius;
      u.uBias.value = p.ao.bias;
      this.pass(this.mAO, this.aoRT);
    }

    const pu = this.mPrep.uniforms;
    pu.tColor.value = this.sceneRT.texture;
    pu.tDepth.value = this.sceneRT.depthTexture;
    pu.tAO.value = this.aoRT.texture;
    pu.uNear.value = camera.near;
    pu.uFar.value = camera.far;
    pu.uUseAO.value = useAO ? 1 : 0;
    pu.uAOStrength.value = p.ao ? p.ao.strength : 0;
    pu.uUseDof.value = p.dof ? 1 : 0;
    if (p.dof) {
      pu.uFocus.value = p.dof.focus;
      pu.uAperture.value = p.dof.aperture;
      pu.uMaxCoc.value = p.dof.maxCoc;
      pu.uNearScale.value = p.dof.nearScale ?? 1;
    }
    this.pass(this.mPrep, this.prepRT);

    let color: THREE.Texture = this.prepRT.texture;
    if (p.dof) {
      const du = this.mDof.uniforms;
      du.tPrep.value = this.prepRT.texture;
      du.uMaxR.value = p.dof.maxCoc * this.height;
      // keep sample density roughly constant in pixels across resolutions
      du.uN.value = Math.min(200, Math.round(56 * Math.max(1, this.height / 720)));
      this.pass(this.mDof, this.dofHalfRT);
      const cu = this.mDofCombine.uniforms;
      cu.tPrep.value = this.prepRT.texture;
      cu.tHalf.value = this.dofHalfRT.texture;
      this.pass(this.mDofCombine, this.dofRT);
      color = this.dofRT.texture;
    }

    // bloom chain
    const dm = this.mDown.uniforms;
    let src: THREE.Texture = color;
    let sw = this.width, sh = this.height;
    for (let i = 0; i < this.down.length; i++) {
      dm.tSrc.value = src;
      dm.uTexel.value.set(1 / sw, 1 / sh);
      dm.uPrefilter.value = i === 0 ? 1 : 0;
      dm.uThreshold.value = p.bloomThreshold;
      dm.uKnee.value = p.bloomKnee;
      this.pass(this.mDown, this.down[i]);
      src = this.down[i].texture;
      sw = this.down[i].width;
      sh = this.down[i].height;
    }
    const um = this.mUp.uniforms;
    let coarse = this.down[this.down.length - 1];
    for (let i = this.down.length - 2; i >= 0; i--) {
      um.tCoarse.value = coarse.texture;
      um.tFine.value = this.down[i].texture;
      um.uTexel.value.set(1 / coarse.width, 1 / coarse.height);
      um.uRadius.value = p.bloomRadius;
      this.pass(this.mUp, this.up[i]);
      coarse = this.up[i];
    }

    const cu = this.mComposite.uniforms;
    cu.tColor.value = color;
    cu.tBloom.value = this.up[0].texture;
    cu.uBloom.value = p.bloomStrength;
    cu.uExposure.value = p.exposure;
    cu.uVignette.value = p.vignette;
    cu.uGrain.value = p.grain;
    cu.uGrainFade.value = p.grainFadeLum;
    cu.uSat.value = p.saturation ?? 1;
    cu.uLift.value = p.lift ?? 0;
    cu.uTint.value.copy(p.tint ?? new THREE.Color(1, 1, 1));
    cu.uFrame.value = frame >>> 0;
    this.pass(this.mComposite, null);
  }

  dispose() {
    [this.sceneRT, this.aoRT, this.prepRT, this.dofHalfRT, this.dofRT, ...this.down, ...this.up].forEach((t) => t.dispose());
    [this.mAO, this.mPrep, this.mDof, this.mDofCombine, this.mDown, this.mUp, this.mComposite].forEach((m) => m.dispose());
  }
}
