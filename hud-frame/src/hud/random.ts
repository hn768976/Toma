/** Deterministic 32-bit PRNG. Remotion renders frames out of order across
 *  threads, so nothing may depend on call order at render time — schedules are
 *  built once at module scope from a fixed seed. */
export const mulberry32 = (seed: number) => {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};
