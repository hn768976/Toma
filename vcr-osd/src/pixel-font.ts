/**
 * Hand-defined 5x7 bitmap font.
 *
 * Every character is a literal pixel grid: 7 rows of 5 columns, "#" for a lit
 * cell. The renderer turns each lit cell into an exact filled rectangle sized
 * in whole device pixels, which is what keeps the letterforms crisp at any
 * output resolution. Rendering a real font small and upscaling would give soft
 * edges and half-lit pixels — the thing this file exists to avoid.
 */

