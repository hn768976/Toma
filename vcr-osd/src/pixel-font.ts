export type PixelMatrix = boolean[][];

const toMatrix = (rows: string[]): PixelMatrix =>
  rows.map((row) => row.split("").map((cell) => cell === "#"));

const MATRICES: Record<string, PixelMatrix> = Object.fromEntries(
  Object.entries(GLYPHS).map(([char, rows]) => [char, toMatrix(rows)]),
);

export const charMatrix = (char: string): PixelMatrix =>
  MATRICES[char.toUpperCase()] ?? MATRICES[" "];

/** Width of a rendered string, in grid cells. */
export const labelWidthInCells = (label: string): number =>
  label.length === 0
    ? 0
    : label.length * FONT_COLS + (label.length - 1) * LETTER_SPACING;
