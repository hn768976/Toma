const merge = (over: DeepPartial<Omit<Look, "id" | "file" | "seed" | "stillFrames">>) => {
  const out = structuredClone(BASE) as Omit<Look, "id" | "file" | "seed" | "stillFrames">;
  for (const key of Object.keys(over) as (keyof typeof out)[]) {
    Object.assign(out[key] as object, over[key] as object);
  }
  return out;
};

