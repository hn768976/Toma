/**
 * Regenerates src/currency-world/world-dots.ts — the dot-matrix world map.
 *
 * The dots are baked into the repo so that rendering never needs the map
 * sources. Re-run only when the grid resolution changes:
 *
 *   npm i --no-save d3-geo topojson-client world-atlas
 *   node scripts/generate-world-dots.mjs
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoEquirectangular, geoContains } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/land-110m.json");
const land = feature(topo, topo.objects.land);

// Equirectangular, Antarctica and the high Arctic clipped off — the same
// framing stock "digital world map" plates use.
const LON_SPAN = 360;
const LAT_MIN = -58;
const LAT_MAX = 82;

const COLS = 176;
const ROWS = Math.round((COLS * (LAT_MAX - LAT_MIN)) / LON_SPAN);

const projection = geoEquirectangular()
  .translate([0, 0])
  .scale(180 / Math.PI)
  .rotate([0, 0]);

const dots = [];
for (let row = 0; row < ROWS; row++) {
  for (let col = 0; col < COLS; col++) {
    // Sample the centre of each cell.
    const lon = -180 + ((col + 0.5) / COLS) * LON_SPAN;
    const lat = LAT_MAX - ((row + 0.5) / ROWS) * (LAT_MAX - LAT_MIN);
    if (!geoContains(land, [lon, lat])) continue;
    dots.push([col, row]);
  }
}

void projection;

const flat = dots.flat().join(",");
const out = `// GENERATED by scripts/generate-world-dots.mjs — do not edit by hand.
// Land cells of a ${COLS}x${ROWS} equirectangular grid (lat ${LAT_MIN}..${LAT_MAX}),
// stored as a flat [col, row, col, row, ...] list to keep the file small.

export const DOT_COLS = ${COLS};
export const DOT_ROWS = ${ROWS};

const PACKED = [${flat}];

export type MapDot = { col: number; row: number };

export const WORLD_DOTS: MapDot[] = (() => {
  const out: MapDot[] = [];
  for (let i = 0; i < PACKED.length; i += 2) {
    out.push({ col: PACKED[i], row: PACKED[i + 1] });
  }
  return out;
})();
`;

writeFileSync(new URL("../src/currency-world/world-dots.ts", import.meta.url), out);
console.log(`grid ${COLS}x${ROWS} -> ${dots.length} land dots`);
