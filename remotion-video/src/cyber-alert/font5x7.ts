export type Glyph = {
  width: number;
  // rows[y] is a bitmask; bit x (counting from the left) is lit.
  rows: number[];
};

const toGlyph = (shape: string[], width: number): Glyph => ({
  width,
  rows: shape.map((row) => {
    let mask = 0;
    for (let x = 0; x < row.length; x++) {
      if (row[x] === "1") mask |= 1 << x;
    }
    return mask;
  }),
});

// Regular weight, used for the blue data rows.
const REGULAR = new Map<string, Glyph>();
// Bold weight: every stroke dilated one dot to the right. The headline on
// the reference panel is visibly heavier than the data behind it, and
// dilating the bitmap is how a real sign does it — there is no half-dot.
const BOLD = new Map<string, Glyph>();

for (const [char, shape] of Object.entries(SHAPES)) {
  const regular = toGlyph(shape, GLYPH_W);
  REGULAR.set(char, regular);
  BOLD.set(char, {
    width: GLYPH_W + 1,
    rows: regular.rows.map((mask) => mask | (mask << 1)),
  });
}

const BLANK = REGULAR.get(" ") as Glyph;

export const getGlyph = (char: string, bold: boolean): Glyph => {
  const table = bold ? BOLD : REGULAR;
  return table.get(char.toUpperCase()) ?? BLANK;
};

