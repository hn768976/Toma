# Generates the fixed 64x64 blue-noise dither tile (void-and-cluster, Ulichney 1993)
# and writes it to src/lib/bluenoise.ts as base64. Deterministic (fixed seed).
import numpy as np, base64, os
N = 64; sigma = 1.5
rng = np.random.default_rng(12345)
ax = np.arange(N); d = np.minimum(ax, N - ax)
g1 = np.exp(-(d ** 2) / (2 * sigma ** 2))
K = np.fft.fft2(np.outer(g1, g1))
def energy(b): return np.real(np.fft.ifft2(np.fft.fft2(b) * K))
# initial binary pattern
b = np.zeros((N, N), bool)
b.flat[rng.choice(N * N, N * N // 10, replace=False)] = True
while True:
    e = energy(b.astype(float))
    cl = np.argmax(np.where(b, e, -np.inf)); b.flat[cl] = False
    e = energy(b.astype(float))
    vd = np.argmin(np.where(b, np.inf, e))
    if vd == cl: b.flat[cl] = True; break
    b.flat[vd] = True
rank = np.zeros(N * N, int); ones = b.sum()
proto = b.copy(); bb = proto.copy()
for r in range(ones - 1, -1, -1):
    e = energy(bb.astype(float)); cl = np.argmax(np.where(bb, e, -np.inf)); bb.flat[cl] = False; rank[cl] = r
bb = proto.copy()
for r in range(ones, N * N):
    e = energy(bb.astype(float)); vd = np.argmin(np.where(bb, np.inf, e)); bb.flat[vd] = True; rank[vd] = r
vals = (rank * 256 // (N * N)).astype(np.uint8)
out = os.path.join(os.path.dirname(__file__), '..', 'src', 'lib', 'bluenoise.ts')
with open(out, 'w') as f:
    f.write('// Fixed 64x64 blue-noise tile (void-and-cluster), generated by scripts/gen_bluenoise.py.\n')
    f.write('export const BLUE_NOISE_SIZE = 64;\n')
    f.write('export const BLUE_NOISE_B64 =\n  "' + base64.b64encode(vals.tobytes()).decode() + '";\n')
print('ok', vals.min(), vals.max(), np.bincount(vals).std())
